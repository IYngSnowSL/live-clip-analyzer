def _get_converter():
    """惰性探测 zhconv（装了就用词组级转换）。"""
    global _ZHCONV, _ZHCONV_CHECKED
    if not _ZHCONV_CHECKED:
        _ZHCONV_CHECKED = True
        try:
            import zhconv  # type: ignore[import-not-found]
            _ZHCONV = zhconv
        except ImportError:
            _ZHCONV = None
    return _ZHCONV


def to_simplified(text: str) -> str:
    """把文本转换为简体中文（已是简体的文本不受影响）。"""
    if not text:
        return text
    conv = _get_converter()
    if conv is not None:
        try:
            return conv.convert(text, "zh-cn")
        except Exception:  # noqa: BLE001
            pass
    global _WARNED
    if not _WARNED:
        _WARNED = True
        print("[text] 未安装 zhconv，使用内置常用字表做繁→简转换"
              "（词组级准确转换请执行：pip install zhconv）")
    return text.translate(_T2S_TABLE)


def has_traditional(text: str) -> bool:
    """判断文本是否仍含本表收录的繁体字（用于校验/日志）。"""
    if not text:
        return False
    return any(ch in _T2S_MAP for ch in text)
